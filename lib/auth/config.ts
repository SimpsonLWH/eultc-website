import "server-only";

import { mongodbAdapter } from "@better-auth/mongo-adapter";
import { betterAuth } from "better-auth";
import { APIError, createAuthMiddleware } from "better-auth/api";
import { nextCookies } from "better-auth/next-js";
import { admin } from "better-auth/plugins";
import { MongoClient } from "mongodb";

import { getUserRoleByEmail } from "@/lib/db";
import { PasswordResetLinkModel } from "@/lib/db/models/password-reset-link";
import {
  evaluateRegistrationAccess,
  normalizeEmail,
} from "@/lib/membership/policy";
import { getActiveInvite, isPaidMember } from "@/lib/membership";

const isBuild = process.env.NEXT_PHASE === "phase-production-build";

function requiredEnvironment(name: string, buildFallback: string): string {
  const value = process.env[name]?.trim();
  if (value) {
    return value;
  }
  if (isBuild) {
    return buildFallback;
  }
  throw new Error(`${name} is required.`);
}

export const authSecret = requiredEnvironment(
  "BETTER_AUTH_SECRET",
  "build-only-secret-not-for-runtime-use"
);
const baseURL = requiredEnvironment(
  "BETTER_AUTH_URL",
  "http://localhost:3000"
);
const mongoUri = requiredEnvironment(
  "MONGODB_URI",
  "mongodb://127.0.0.1:27017/eultc-build"
);

const mongoClient = new MongoClient(mongoUri);
export const authDatabase = mongoClient.db();

export const INTERNAL_RESET_HEADER = "x-eultc-internal-reset";
export const RESET_ADMIN_HEADER = "x-eultc-reset-admin";
const RESET_LINK_TTL_MS = 60 * 60 * 1000;

export const auth = betterAuth({
  appName: "EULTC Clubhouse",
  baseURL,
  secret: authSecret,
  trustedOrigins: [baseURL],
  database: mongodbAdapter(authDatabase),
  emailAndPassword: {
    enabled: true,
    minPasswordLength: 12,
    maxPasswordLength: 128,
    autoSignIn: true,
    resetPasswordTokenExpiresIn: 60 * 60,
    revokeSessionsOnPasswordReset: true,
    sendResetPassword: async ({ user, url }, request) => {
      const createdBy = request?.headers.get(RESET_ADMIN_HEADER)?.trim();
      if (!createdBy) {
        throw new APIError("FORBIDDEN", {
          message: "Password reset links can only be generated by a captain.",
        });
      }

      await PasswordResetLinkModel.findOneAndUpdate(
        { userId: user.id },
        {
          $set: {
            userId: user.id,
            email: normalizeEmail(user.email),
            url,
            createdBy,
            expiresAt: new Date(Date.now() + RESET_LINK_TTL_MS),
            usedAt: null,
          },
        },
        { upsert: true, new: true, setDefaultsOnInsert: true }
      );
    },
    onPasswordReset: async ({ user }) => {
      await PasswordResetLinkModel.deleteOne({ userId: user.id });
    },
  },
  rateLimit: {
    enabled: true,
    window: 60,
    max: 100,
  },
  databaseHooks: {
    user: {
      create: {
        before: async (user) => {
          const userRole = await getUserRoleByEmail(user.email);
          return {
            data: {
              ...user,
              role: userRole?.role === "admin" ? "admin" : "player",
            },
          };
        },
      },
    },
  },
  hooks: {
    before: createAuthMiddleware(async (context) => {
      if (context.path === "/sign-up/email") {
        const email = String(context.body?.email ?? "");
        const inviteCode = String(context.body?.inviteCode ?? "");
        const [invite, userRole] = await Promise.all([
          getActiveInvite(),
          getUserRoleByEmail(email),
        ]);
        const access = evaluateRegistrationAccess({
          email,
          inviteCode,
          activeInviteCode: invite?.code ?? null,
          isPaid: await isPaidMember(email),
          isAdmin: userRole?.role === "admin",
        });

        if (!access.allowed) {
          const message =
            access.reason === "invalid_invite"
              ? "This registration link is no longer valid."
              : access.reason === "not_paid"
                ? "That email is not on the paid membership list."
                : "Enter a valid email address.";
          throw new APIError("FORBIDDEN", { message });
        }
        return;
      }

      if (context.path === "/sign-in/email") {
        const email = String(context.body?.email ?? "");
        const userRole = await getUserRoleByEmail(email);
        if (userRole?.role !== "admin" && !(await isPaidMember(email))) {
          throw new APIError("UNAUTHORIZED", {
            message: "Unable to sign in with those details.",
          });
        }
        return;
      }

      if (context.path === "/request-password-reset") {
        if (context.headers?.get(INTERNAL_RESET_HEADER) !== authSecret) {
          throw new APIError("FORBIDDEN", {
            message: "Password reset links are generated by a captain.",
          });
        }
      }
    }),
  },
  plugins: [
    admin({
      defaultRole: "player",
      adminRoles: ["admin"],
    }),
    nextCookies(),
  ],
});
